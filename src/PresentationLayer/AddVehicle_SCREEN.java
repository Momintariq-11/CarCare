    /**
     * Saves Customer and Vehicle into database
     */
    private void registerAndSave() {
        String name  = txtFullName.getText().trim();
        String phone = jTextField2.getText().trim();
        String regNo = txtFullName1.getText().trim();

        // 1. Validation (required fields)
        if (name.isEmpty() || phone.isEmpty() || regNo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all required fields!");
            return;
        }

        // 2. Validation (exact 11 digits phone)
        if (phone.length() != 11) {
            JOptionPane.showMessageDialog(this, "Phone must be exactly 11 digits (e.g. 03001234567)!");
            return;
        }

        try {
            // 3. Save Customer first -> get auto-generated ID
            Customer c = new Customer(name, phone, jTextField3.getText().trim(), jTextField4.getText().trim());
            int custId = new Customer_DAO().addCustomer(c);

            if (custId == -1) {
                JOptionPane.showMessageDialog(this, "Failed to save customer!");
                return;
            }

            // 4. Save Vehicle with Customer ID
            int year = Integer.parseInt(jTextField7.getText().trim());
            int mileage = Integer.parseInt(jTextField8.getText().trim());
            Vehicle v = new Vehicle(custId, regNo, jTextField5.getText().trim(), jTextField6.getText().trim(), year, mileage);

            if (new Vehicle_DAO().addVehicle(v)) {
                JOptionPane.showMessageDialog(this, "Vehicle Registered Successfully!");
                dispose(); // Close dialog, table refreshes automatically
            } else {
                JOptionPane.showMessageDialog(this, "Failed to save vehicle!");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Year and Mileage must be valid numbers!");
        }
    }

