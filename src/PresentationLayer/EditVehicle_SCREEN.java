    /**
     * Fills the fields with selected vehicle data
     */
    public void setVehicleData(Vehicle v) {
        if (v == null) return;

        txtRegNo.setText(v.getRegistrationNo());
        txtMake.setText(v.getMake());
        txtModel.setText(v.getModel());
        txtYear.setText(String.valueOf(v.getVehicleYear()));
        txtMileage.setText(String.valueOf(v.getMileage()));
        txtCustomer.setText(v.getCustomerName());

        //Customer cannot be changed here
        
        txtCustomer.setEditable(false);
    }

    /**
     * Saves updated vehicle details into database
     */
    private void saveChanges() {
        String regNo = txtRegNo.getText().trim();
        String make = txtMake.getText().trim();
        String model = txtModel.getText().trim();
        String year = txtYear.getText().trim();
        String mileage = txtMileage.getText().trim();

        // 1. Check empty fields
        if (make.isEmpty() || model.isEmpty() || year.isEmpty() || mileage.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields!");
            return;
        }

        // 2. Validate numbers and update database
        try {
            int y = Integer.parseInt(year);
            int m = Integer.parseInt(mileage);

            Vehicle_DAO dao = new Vehicle_DAO();
            if (dao.updateVehicle(regNo, make, model, y, m)) {
                JOptionPane.showMessageDialog(this, "Vehicle updated successfully!");
                dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Database update failed!");
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Year and Mileage must be numbers!");
        }
    }

