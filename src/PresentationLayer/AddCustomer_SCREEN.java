    /**
     * Customer ki details database mein save karna
     */
    private void saveChanges() {
        String name = txtFullName.getText().trim();
        String phone = txtPhone.getText().trim();
        String email = txtEmail.getText().trim();
        String address = txtAddress.getText().trim();

        // 1. Check koi box khali na ho
        if (name.isEmpty() || phone.isEmpty() || email.isEmpty() || address.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields!");
            return;
        }

        // 2. Check phone 11 digits ho
        if (phone.length() != 11) {
            JOptionPane.showMessageDialog(this, "Phone must be exactly 11 digits (e.g. 03001234567)!");
            return;
        }

        // 3. Database mein add karein
        Customer newCustomer = new Customer(name, phone, email, address);
        Customer_DAO dao = new Customer_DAO();

        if (dao.addCustomer(newCustomer) > 0) {
            JOptionPane.showMessageDialog(this, "Customer added successfully!");
            dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Database insert failed!");
        }
    }

