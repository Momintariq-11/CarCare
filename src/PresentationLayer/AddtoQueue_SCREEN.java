    // Step 1: Search car in database by Registration Number
    private void verifyCar() {
        String reg = txtRegNo.getText().trim();
        vehicle = new Vehicle_DAO().getVehicleByRegNo(reg);

        jLabel3.setOpaque(true); // Needed in Swing for background colors to show

        if (vehicle != null) {
            // TURN GREEN
            jLabel3.setText("Found: " + vehicle.getMake() + " " + vehicle.getModel() + " • Owner: " + vehicle.getCustomerName());
            jLabel3.setBackground(new java.awt.Color(220, 252, 231)); // Soft Green background
            jLabel3.setForeground(new java.awt.Color(22, 101, 52));   // Dark Green text
            btnSave.setEnabled(true);
        } else {
            // TURN RED
            jLabel3.setText("Car not found! Please register car first.");
            jLabel3.setBackground(new java.awt.Color(254, 226, 226)); // Soft Red background
            jLabel3.setForeground(new java.awt.Color(153, 27, 27));   // Dark Red text
            btnSave.setEnabled(false);
        }
    }

    // Step 2: Save verified car into Service Queue
    private void addToQueue() {
        String service = jComboBox1.getSelectedItem().toString();
        String mechanic = jComboBox3.getSelectedItem().toString();

        if (new ServiceQueue_DAO().addToQueue(vehicle.getVehicleId(), service, mechanic)) {
            added = true;
            JOptionPane.showMessageDialog(this, "Car added to Queue successfully!");
            dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to add car to queue!");
        }
    }

    public boolean isQueueAdded() {
        return added;
    }

