    /**
     * Handles credential verification and screen transition.
     */
    private void handleLogin() {
        String email = jTextField1.getText().trim();
        String password = new String(jPasswordField1.getPassword()).trim();

        if (email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your email.", "Login", JOptionPane.WARNING_MESSAGE);
            jTextField1.requestFocus();
            return;
        }

        if (password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your password.", "Login", JOptionPane.WARNING_MESSAGE);
            jPasswordField1.requestFocus();
            return;
        }

        boolean loginSuccessful = loginBLL.login(email, password);
        if (loginSuccessful) {
            VehicleManagement_Screen mainScreen = new VehicleManagement_Screen();
            mainScreen.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Invalid email or password.", "Login Failed", JOptionPane.ERROR_MESSAGE);
        }
    }

